do $$
begin
    if to_regclass('public.reference_brands') is null
       or to_regclass('public.reference_material_families') is null then
        raise exception 'Apply the Catalog V2 foundation and Global family seed first';
    end if;
end $$;

create table if not exists public.reference_brand_product_systems (
    product_system_id uuid primary key default gen_random_uuid(),
    brand_id uuid not null references public.reference_brands(brand_id),
    family_id uuid not null references public.reference_material_families(family_id),
    product_system_code text not null unique check (
        product_system_code = lower(product_system_code)
        and product_system_code !~ '[^a-z0-9_]'
    ),
    system_kind text not null check (system_kind in (
        'drawer_runner', 'drawer_system', 'hinge_system', 'lift_system',
        'door_system', 'storage_system', 'connector_system'
    )),
    canonical_name text not null check (length(trim(canonical_name)) between 1 and 240),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (product_system_id, brand_id, family_id),
    unique (brand_id, family_id, canonical_name),
    foreign key (family_id, brand_id)
        references public.reference_material_family_brand_scopes(family_id, brand_id)
);

create table if not exists public.reference_brand_product_system_aliases (
    product_system_alias_id uuid primary key default gen_random_uuid(),
    product_system_id uuid not null references public.reference_brand_product_systems(product_system_id)
        on delete cascade,
    market_code text references public.reference_markets(market_code),
    language_code text,
    alias_text text not null check (length(trim(alias_text)) between 1 and 240),
    alias_key text not null check (length(trim(alias_key)) between 1 and 240),
    active boolean not null default true,
    created_at timestamptz not null default now()
);

create unique index if not exists reference_brand_product_system_aliases_lookup_uniq
    on public.reference_brand_product_system_aliases (
        product_system_id, coalesce(market_code, ''), alias_key
    );
create index if not exists reference_brand_product_system_aliases_lookup_idx
    on public.reference_brand_product_system_aliases (market_code, alias_key)
    where active;

